"""Hash-check production timing pairs and reduce warmed Nsight kernel traces.
Usage: python3 summarize_production_fft.py EVIDENCE OUTPUT.json
SQLite files are regenerated by nsys stats from the archived reports.
"""
import hashlib
import json
from pathlib import Path
import sqlite3
import sys
import tomllib
import numpy as np


def read_rate(root, meta):
    path=root/meta['rate_file'];data=path.read_bytes()
    assert hashlib.sha256(data).hexdigest()==meta['output_sha256']
    values=np.frombuffer(data,dtype='<f4').astype(np.float64)
    assert values.size==np.prod(meta['output_shape'])
    return values


def profile(path, replays=4):
    connection=sqlite3.connect(f'file:{path}?mode=ro',uri=True)
    rows=connection.execute('SELECT k.start,k.end,k.graphNodeId,s.value FROM CUPTI_ACTIVITY_KIND_KERNEL k JOIN StringIds s ON k.demangledName=s.id').fetchall()
    nodes={}
    totals={}
    for start,end,node,name in rows:
        nodes[node]=nodes.get(node,0)+1
        if 'pyramid_modulation_transpose_kernel' in name:category='transpose'
        elif 'pyramid_modulation_transposed_mask_kernel' in name or 'pyramid_modulation_batch_mask_kernel' in name:category='mask'
        elif 'pyramid_modulation_batch_intensity_kernel' in name:category='intensity'
        elif 'pyramid_pupil_modulation_batch_kernel' in name:category='fill'
        elif 'pyramid_pupil_phase_kernel' in name:category='pupil_phase'
        elif 'bin2d_kernel' in name:category='bin'
        elif 'fft' in name:category='fft'
        else:raise AssertionError(name)
        entry=totals.setdefault(category,{'instances':0,'total_ns':0})
        entry['instances']+=1;entry['total_ns']+=end-start
    assert all(count==replays for count in nodes.values())
    for entry in totals.values():
        entry['mean_frame_ms']=entry['total_ns']/replays/1e6
    tables={row[0] for row in connection.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    memsets=connection.execute('SELECT count(*) FROM CUPTI_ACTIVITY_KIND_MEMSET').fetchone()[0]
    copies=connection.execute('SELECT count(*) FROM CUPTI_ACTIVITY_KIND_MEMCPY').fetchone()[0] if 'CUPTI_ACTIVITY_KIND_MEMCPY' in tables else 0
    result={'replays':replays,'kernel_instances':len(rows),'distinct_kernel_nodes':len(nodes),
            'memset_instances':memsets,'recorded_memcpy_instances':copies,'stages':totals,
            'kernel_busy_fraction_of_recorded_span':sum(end-start for start,end,_,_ in rows)/(max(row[1] for row in rows)-min(row[0] for row in rows))}
    connection.close()
    return result


def summarize(root):
    result={'scope':'Completed unpaced captured optical node; shared host, uncontrolled clocks; not WCET or fixed-rate latency','cases':{}}
    for case,before_batch in (('gpi_fine',4),('copper_fine',2)):
        records={version:[tomllib.loads((root/f'production-{version}-{case}-r{round}.toml').read_text()) for round in (1,2)] for version in ('before','after')}
        values={version:[read_rate(root,meta) for meta in metas] for version,metas in records.items()}
        for version,metas in records.items():
            assert np.array_equal(values[version][0],values[version][1])
            for meta in metas:
                assert meta['batch']==(before_batch if version=='before' else 16)
                assert all(x==0 for x in meta['host_allocated_bytes'])
        old,new=values['before'][0],values['after'][0]
        relative=float(np.linalg.norm(new-old)/np.linalg.norm(old))
        flux=float(abs(new.sum()/old.sum()-1))
        assert relative<2e-6 and flux<2e-6
        data={'relative_l2':relative,'flux_relative_error':flux,'timings':{}}
        for version,metas in records.items():
            data['timings'][version]={'round_medians_ms':[m['median_ms'] for m in metas],
                'median_of_round_medians_ms':float(np.median([m['median_ms'] for m in metas])),
                'field_stack_bytes':metas[0]['field_stack_bytes'],'extra_fft_array_bytes':metas[0]['extra_fft_array_bytes'],
                'observed_pool_bytes':[m['device_used_bytes'] for m in metas]}
        data['reduction_percent']=100*(1-data['timings']['after']['median_of_round_medians_ms']/data['timings']['before']['median_of_round_medians_ms'])
        assert ('PyramidTransposeFFTWorkspace' in records['after'][0]['fft_workspace_type']) == (case=='gpi_fine')
        data['profiles']={version:profile(root/f'trace-{version}-{case}.sqlite') for version in ('before','after')}
        result['cases'][case]=data
    return result


if __name__=='__main__':
    if len(sys.argv)!=3:raise SystemExit(__doc__)
    Path(sys.argv[2]).write_text(json.dumps(summarize(Path(sys.argv[1])),indent=2)+'\n')
